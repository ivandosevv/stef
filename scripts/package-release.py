"""Create an unsigned macOS ARM64 archive and an exact-checksum Brew recipe."""
import argparse
import hashlib
from pathlib import Path
import platform
import tarfile

parser = argparse.ArgumentParser()
parser.add_argument("--url-prefix", help="Published archive base URL; default is a local file URL")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
if platform.system() != "Darwin" or platform.machine() != "arm64":
    raise SystemExit("The current native release target is macOS ARM64")
version = "0.3.0"
binary = root / "bin/stef"
if not binary.is_file():
    raise SystemExit("Run make build first")
output = root / "artifacts"
output.mkdir(exist_ok=True)
archive = output / f"stef-{version}-darwin-arm64.tar.gz"
with tarfile.open(archive, "w:gz") as bundle:
    bundle.add(binary, arcname="stef")
    bundle.add(root / "LICENSE", arcname="LICENSE")
    bundle.add(root / ".agents/skills/stef", arcname="skills/stef")
checksum = hashlib.sha256(archive.read_bytes()).hexdigest()
(output / (archive.name + ".sha256")).write_text(f"{checksum}  {archive.name}\n")
url = args.url_prefix.rstrip("/") + "/" + archive.name if args.url_prefix else archive.as_uri()
formula = root / "packaging/homebrew/Formula/stef.rb"
formula.parent.mkdir(parents=True, exist_ok=True)
formula.write_text(f'''# Generated by scripts/package-release.py. This URL has not been published.
class Stef < Formula
  desc "Interactive local companion for coding agents"
  homepage "https://github.com/ivandosevv/stef"
  url "{url}"
  version "{version}"
  sha256 "{checksum}"
  license "MIT"

  depends_on :macos
  depends_on arch: :arm64

  def install
    bin.install "stef"
    pkgshare.install "skills"
  end

  test do
    assert_match "Run stdio MCP", shell_output("#{{bin}}/stef --help 2>&1")
  end
end
''')
print(f"Archive: {archive}\nSHA256: {checksum}\nDraft Brew recipe: {formula}")
